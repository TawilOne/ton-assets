# -------------------------------------------------------------------
# /count — сколько пар на этой неделе
#
# len(lessons) — длина списка, то есть количество пар.
# Дальше подбираем окончание слова «пара»:
#   * 11, 12, 13, 14 — всегда «пар» (одиннадцать пар, двенадцать пар)
#   * если число кончается на 1 — «пара» (1 пара, 21 пара)
#   * на 2, 3, 4 — «пары» (2 пары, 23 пары)
#   * всё остальное — «пар» (5 пар, 10 пар)
# n % 10  — последняя цифра числа, n % 100 — две последние.
# -------------------------------------------------------------------
def count_text(lessons):
    n = len(lessons)

    if 11 <= n % 100 <= 14:
        word = "пар"
    elif n % 10 == 1:
        word = "пара"
    elif n % 10 in (2, 3, 4):
        word = "пары"
    else:
        word = "пар"

    return f"На этой неделе {n} {word}"


# -------------------------------------------------------------------
# /lectures и /labs — только пары нужного типа
#
# Классический шаблон «отфильтровать список»:
#   1. завести пустой список result
#   2. пройтись циклом по всем парам
#   3. если пара подходит — добавить её в result
# -------------------------------------------------------------------
def only_kind(lessons, kind):
    result = []
    for l in lessons:
        if l.kind == kind:
            result.append(l)
    return result


# -------------------------------------------------------------------
# /first — во сколько завтра первая пара
#
# Сначала убираем отменённые пары (тот же шаблон фильтра, что выше).
# Если ничего не осталось — пар нет.
# Иначе берём первую пару: real[0] — первый элемент списка.
# -------------------------------------------------------------------
def first_lesson_text(lessons):
    real = []
    for l in lessons:
        if not l.cancelled:
            real.append(l)

    if len(real) == 0:
        return "Завтра пар нет, можно выспаться 😴"

    first = real[0]
    text = f"Первая пара в {first.start}: {first.subject}"
    if first.room:
        text += f", ауд. {first.room}"
    return text


# -------------------------------------------------------------------
# /stats — сколько пар по каждому предмету
#
# 1. Считаем в словаре: ключ — предмет, значение — сколько раз встретился.
#    counts.get(предмет, 0) — взять текущее число, а если предмета ещё
#    нет в словаре — 0.
# 2. Сортируем: самые частые предметы — первыми.
#    sorted(..., key=..., reverse=True) — сортировка по убыванию;
#    item[1] — это число (item[0] — название предмета).
# 3. Собираем строки и склеиваем их через перенос строки.
# -------------------------------------------------------------------
def stats_text(lessons):
    counts = {}
    for l in lessons:
        counts[l.subject] = counts.get(l.subject, 0) + 1

    if len(counts) == 0:
        return "Пар не найдено"

    def how_many(item):
        return item[1]

    lines = []
    for subject, n in sorted(counts.items(), key=how_many, reverse=True):
        lines.append(f"{subject} — {n}")
    return "\n".join(lines)


# -------------------------------------------------------------------
# /free — свободные дни недели
#
# 1. Собираем список дней, в которые пары ЕСТЬ (busy).
# 2. Из всех дней с понедельника по субботу оставляем те,
#    которых нет в busy.
# -------------------------------------------------------------------
def free_days(lessons):
    days = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота"]

    busy = []
    for l in lessons:
        if not l.cancelled:
            busy.append(l.weekday)

    free = []
    for day in days:
        if day not in busy:
            free.append(day)
    return free
