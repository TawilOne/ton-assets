def spec_free(d):
    st = [("", r) for r in d["stairs"]]
    return dict(rows=[], halls=d["halls"], stairs=st, lifts=[("", r) for r in d["lifts"]],
                blocks=d.get("blocks", []), cells=list(d["cells"]), gaps=[], polys=[], doors=[])


def spec_for(f, d):
    if d.get("free"):
        return spec_free(d)
    cores = d["cores"]
    in_core = lambda a, b: any(abs(a - c0) < 1 and abs(b - c1) < 1 for c0, c1 in cores)
    cells = list(d.get("cells", []))
    for walls, labels, y0, y1 in ((d["north"], d["n"], N0, N1), (d["south"], d["s"], S0, S1)):
        for a, b in zip(walls, walls[1:]):
            if in_core(a, b):
                continue
            names = [n for n, x in labels if a <= x < b]
            assert len(names) <= 1, (f, a, b, names)
            name = names[0] if names and names[0] != WC else None
            cells.append((name, (a, y0, b, y1)))
    halls, lifts, stairs = [(d.get("corridor_from", 0), N1, 1000, S0)], [], []
    for i, (c0, c1) in enumerate(cores):
        lx = c1 - 15 if i >= 2 else c0 + 1   # у 3-го и 4-го узла лифты у восточной стены холла
        lifts += [("", (lx, 6, lx + 14, 22)), ("", (lx, 25, lx + 14, 41))]
        halls.append((c0, N0, c1, N1))
        stairs.append(("", (c0, S0, c1, S1)))
    return dict(rows=[], halls=halls, stairs=stairs, lifts=lifts, blocks=d.get("blocks", []), cells=cells,
                gaps=[], polys=[], doors=[])


def main():
    rooms = json.loads((DOCS / "rooms.json").read_text(encoding="utf-8"))
    plans = json.loads((DOCS / "plans.json").read_text(encoding="utf-8"))
    rooms = {k: v for k, v in rooms.items() if not v["plan"].startswith("k2-")}
    plans = {k: v for k, v in plans.items() if not k.startswith("k2-")}
    for f, d in sorted(FLOORS.items(), reverse=True):
        plan = f"k2-{f:g}"
        svg, out, _, (vx, vy, vw, vh), _ = build2.build(f, spec_for(f, d), {}, plan=plan)
        for name, x, y in d.get("marks", []):  # номер без своего помещения на схеме — подпись в коридоре
            svg = svg.replace('</g></svg>', f'<text class="num" data-room="{name}" x="{x}" y="{y}" '
                                            f'font-size="7">{name}</text></g></svg>')
            out[name] = {"plan": plan, "x": round((x - vx) / vw, 4), "y": round((y - vy) / vh, 4)}
        (DOCS / "plans" / f"{plan}.svg").write_text(svg, encoding="utf-8")
        plans[plan] = f"plans/{plan}.svg?v={hashlib.md5(svg.encode()).hexdigest()[:8]}"
        rooms.update(out)
        print(f"2 корпус, этаж {f}: кабинетов {len(out)}")
    (DOCS / "rooms.json").write_text(json.dumps(dict(sorted(rooms.items())), ensure_ascii=False, indent=1),
                                     encoding="utf-8")
    (DOCS / "plans.json").write_text(json.dumps(dict(sorted(plans.items())), ensure_ascii=False, indent=1),
                                     encoding="utf-8")


if __name__ == "__main__":
    main()
