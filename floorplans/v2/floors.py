"""Описание этажей главного корпуса (поверх общего скелета building.floor()).
Координаты — в общей системе (канон): крылья x 0–134 и 866–1000, y 0–455; центр y 184–315.
Пристройки у торцов крыльев (x < 0 и x > 1000) есть на 1–4 этажах; снято по выпрямленным фото."""
from building import floor


def annex(x0, x1, y0, y1, c0, c1):
    """Пристройка с коридором по середине (y c0–c1) и кабинетами по обе стороны.
    Коридор пристройки сквозным проходом выходит в коридор крыла."""
    through = (0, c0, 56, c1) if x1 <= 0 else (946, c0, 1000, c1)
    return dict(rows=[(x0, y0, x1, c0, "x"), (x0, c1, x1, y1, "x")], halls=[(x0, c0, x1, c1)],
                gaps=[through])


