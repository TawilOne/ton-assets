H = {}
for f, pts in PTS.items():
    keys = list(pts)
    H[f] = homography([orig(f, pts[k]) for k in keys], [CANON[k] for k in keys])


def to_canon(f, x, y):
    return tuple(float(v) for v in apply(H[f], (x, y)))


def ocr_to_canon(f, fx, fy):
    x0, y0, x1, y1 = OLDBOX[f]
    return to_canon(f, x0 + fx * (x1 - x0), y0 + fy * (y1 - y0))


